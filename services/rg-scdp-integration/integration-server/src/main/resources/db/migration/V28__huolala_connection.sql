CREATE TABLE integration_huolala_connector (
    id BINARY(16) NOT NULL COMMENT '连接ID',
    tenant_id BINARY(16) NOT NULL COMMENT '租户ID',
    enterprise_id VARCHAR(80) NOT NULL COMMENT '货拉拉企业ID',
    config_json JSON NOT NULL COMMENT '非敏感连接配置',
    auth_status VARCHAR(20) NOT NULL DEFAULT 'UNAUTHORIZED' COMMENT '授权状态',
    token_secret_ref VARCHAR(200) NULL COMMENT '加密令牌文件引用，不保存明文令牌',
    token_expires_at DATETIME(6) NULL COMMENT '令牌到期时间UTC',
    auth_state_hash CHAR(64) NULL COMMENT '一次性授权校验摘要',
    auth_actor_id BINARY(16) NULL COMMENT '发起授权的管理员',
    auth_expires_at DATETIME(6) NULL COMMENT '授权流程有效期UTC',
    enabled TINYINT NOT NULL DEFAULT 0 COMMENT '自动同步开关',
    next_sync_at DATETIME(6) NULL COMMENT '下次自动同步时间UTC',
    lease_id VARCHAR(36) NULL COMMENT '正在执行的任务ID',
    lease_expires_at DATETIME(6) NULL COMMENT '分布式租约有效期UTC',
    last_success_at DATETIME(6) NULL COMMENT '最近成功时间UTC',
    last_error VARCHAR(500) NULL COMMENT '脱敏后的业务错误',
    revision BIGINT NOT NULL DEFAULT 1 COMMENT '乐观锁',
    created_by BINARY(16) NOT NULL COMMENT '创建人',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间UTC',
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '更新时间UTC',
    PRIMARY KEY(id),
    UNIQUE KEY uk_hll_tenant(tenant_id),
    KEY ix_hll_schedule(enabled,next_sync_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='货拉拉企业连接，复用通用原始回执、映射、审计和同步批次';
