ALTER TABLE crm_store_ownership
 ADD COLUMN next_check_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 ADD KEY ix_ownership_check(ended_at,next_check_at,id);

CREATE TABLE crm_visit (
 id BIGINT NOT NULL,
 tenant_id VARCHAR(64) NOT NULL,
 revision BIGINT NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 created_by VARCHAR(64) NOT NULL,
 updated_by VARCHAR(64) NOT NULL,
 store_id BIGINT NOT NULL,
 ownership_id BIGINT NOT NULL,
 salesperson_id BIGINT NOT NULL,
 department_id_snapshot BIGINT NULL,
 work_mode VARCHAR(24) NOT NULL DEFAULT 'OWNER',
 status_code VARCHAR(24) NOT NULL DEFAULT 'IN_PROGRESS',
 visited_at DATETIME(6) NOT NULL,
 accepted_at DATETIME(6) NOT NULL,
 checkin_accepted_at DATETIME(6) NOT NULL,
 checked_out_at DATETIME(6) NULL,
 qualified_at DATETIME(6) NULL,
 submitted_at DATETIME(6) NULL,
 reviewed_at DATETIME(6) NULL,
 reviewer_user_id VARCHAR(64) NULL,
 review_reason VARCHAR(1000) NULL,
 checkin_longitude DECIMAL(10,7) NOT NULL,
 checkin_latitude DECIMAL(10,7) NOT NULL,
 checkin_coordinate_system VARCHAR(16) NOT NULL,
 accuracy_meters DECIMAL(10,2) NULL,
 distance_meters DECIMAL(10,2) NOT NULL,
 store_snapshot JSON NOT NULL,
 result_summary VARCHAR(2000) NULL,
 validation_policy_version VARCHAR(32) NOT NULL,
 request_id VARCHAR(64) NOT NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uk_visit_tenant(tenant_id,id),
 UNIQUE KEY uk_visit_request(tenant_id,request_id),
 KEY ix_visit_store(tenant_id,store_id,status_code,visited_at,id),
 KEY ix_visit_ownership(tenant_id,ownership_id,status_code,qualified_at),
 KEY ix_visit_employee(tenant_id,salesperson_id,visited_at,id),
 FOREIGN KEY(tenant_id,store_id) REFERENCES crm_store_master(tenant_id,id),
 FOREIGN KEY(tenant_id,ownership_id) REFERENCES crm_store_ownership(tenant_id,id),
 CHECK(status_code IN ('IN_PROGRESS','SUBMITTED','EFFECTIVE','INVALID','VOID')),
 CHECK(checked_out_at IS NULL OR checked_out_at>=visited_at),
 CHECK(status_code<>'EFFECTIVE' OR (qualified_at IS NOT NULL AND submitted_at IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE crm_visit_evidence (
 id BIGINT NOT NULL,
 tenant_id VARCHAR(64) NOT NULL,
 visit_id BIGINT NOT NULL,
 file_ref VARCHAR(500) NOT NULL,
 evidence_type VARCHAR(24) NOT NULL,
 status_code VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 created_by VARCHAR(64) NOT NULL,
 updated_by VARCHAR(64) NOT NULL,
 revision BIGINT NOT NULL DEFAULT 1,
 PRIMARY KEY(id),
 KEY ix_visit_evidence(tenant_id,visit_id,status_code),
 FOREIGN KEY(tenant_id,visit_id) REFERENCES crm_visit(tenant_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
