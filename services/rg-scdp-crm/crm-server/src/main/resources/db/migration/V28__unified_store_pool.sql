-- Unified company store identity. Public/private/cooperation are independent query dimensions.
-- New feature tables coexist with the legacy crm_store/customer tables until reviewed cutover.
-- No existing customer/store/order/visit data or foreign keys are modified by this migration.

CREATE TABLE crm_store_master (
 id BIGINT NOT NULL,
 tenant_id VARCHAR(64) NOT NULL,
 revision BIGINT NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 created_by VARCHAR(64) NOT NULL,
 updated_by VARCHAR(64) NOT NULL,
 name VARCHAR(200) NOT NULL,
 store_type_code VARCHAR(32) NULL,
 address VARCHAR(500) NOT NULL,
 public_phone VARCHAR(50) NULL,
 admin_area_code CHAR(6) NOT NULL,
 admin_area_version VARCHAR(32) NOT NULL,
 area_resolution VARCHAR(24) NOT NULL,
 longitude DECIMAL(10,7) NULL,
 latitude DECIMAL(10,7) NULL,
 coordinate_system VARCHAR(16) NULL,
 record_status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
 status_reason VARCHAR(500) NULL,
 merged_into_store_id BIGINT NULL,
 table_count SMALLINT UNSIGNED NULL,
 potential_level VARCHAR(16) NOT NULL DEFAULT 'UNKNOWN',
 potential_reason VARCHAR(500) NULL,
 profile_verified_at DATETIME(6) NULL,
 profile_verified_by VARCHAR(64) NULL,
 historical_cooperation_confirmed BOOLEAN NOT NULL DEFAULT false,
 historical_first_cooperated_at DATETIME(6) NULL,
 historical_cooperation_evidence VARCHAR(1000) NULL,
 historical_cooperation_verified_at DATETIME(6) NULL,
 historical_cooperation_verified_by VARCHAR(64) NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uk_store_tenant(tenant_id,id),
 KEY ix_store_area(tenant_id,admin_area_version,admin_area_code,record_status,id),
 KEY ix_store_merge(tenant_id,merged_into_store_id,id),
 CHECK ((longitude IS NULL AND latitude IS NULL AND coordinate_system IS NULL) OR (longitude IS NOT NULL AND latitude IS NOT NULL AND longitude BETWEEN -180 AND 180 AND latitude BETWEEN -90 AND 90 AND coordinate_system IN ('GCJ02','WGS84'))),
 CHECK (record_status IN ('ACTIVE','SUSPENDED','CLOSED','MERGED')),
 CHECK (potential_level IN ('UNKNOWN','HIGH','MEDIUM','LOW'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE crm_store_identity (
 id BIGINT NOT NULL,
