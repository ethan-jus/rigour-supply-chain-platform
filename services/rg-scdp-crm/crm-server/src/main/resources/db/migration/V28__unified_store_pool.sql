CREATE TABLE crm_store_ownership (
 id BIGINT NOT NULL,
 tenant_id VARCHAR(64) NOT NULL,
 revision BIGINT NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 created_by VARCHAR(64) NOT NULL,
 updated_by VARCHAR(64) NOT NULL,
 store_id BIGINT NOT NULL,
 owner_employee_id BIGINT NOT NULL,
 department_id_at_start BIGINT NULL,
 acquire_type VARCHAR(24) NOT NULL,
 started_at DATETIME(6) NOT NULL,
 policy_id BIGINT NOT NULL,
 phase VARCHAR(24) NOT NULL DEFAULT 'FIRST_VISIT',
 last_valid_visit_id BIGINT NULL,
 last_valid_visit_at DATETIME(6) NULL,
 last_valid_order_id BIGINT NULL,
 last_valid_order_at DATETIME(6) NULL,
 deadline_at DATETIME(6) NOT NULL,
 hold_reason VARCHAR(32) NULL,
 hold_until DATETIME(6) NULL,
 ended_at DATETIME(6) NULL,
 end_reason VARCHAR(24) NULL,
 cooldown_until DATETIME(6) NULL,
 request_id VARCHAR(64) NOT NULL,
 active_store_id BIGINT GENERATED ALWAYS AS (CASE WHEN ended_at IS NULL THEN store_id ELSE NULL END) STORED,
 PRIMARY KEY(id),
 UNIQUE KEY uk_ownership_tenant(tenant_id,id),
 UNIQUE KEY uk_ownership_request(tenant_id,request_id),
 UNIQUE KEY uk_ownership_active(tenant_id,active_store_id),
 KEY ix_ownership_owner(tenant_id,owner_employee_id,ended_at,id),
 KEY ix_ownership_deadline(tenant_id,ended_at,deadline_at,id),
 KEY ix_ownership_store(tenant_id,store_id,started_at,id),
 KEY ix_ownership_cooldown(tenant_id,store_id,owner_employee_id,cooldown_until),
 FOREIGN KEY(tenant_id,store_id) REFERENCES crm_store_master(tenant_id,id),
 FOREIGN KEY(tenant_id,policy_id) REFERENCES crm_pool_policy(tenant_id,id),
 CHECK(ended_at IS NULL OR ended_at>=started_at),
 CHECK((ended_at IS NULL AND end_reason IS NULL) OR (ended_at IS NOT NULL AND end_reason IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

