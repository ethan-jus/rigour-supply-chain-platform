 source_batch_ref VARCHAR(64) NULL,
 source_record_ref VARCHAR(500) NULL,
 observed_at DATETIME(6) NULL,
 verified_at DATETIME(6) NOT NULL,
 status_code VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
 PRIMARY KEY(id),
 UNIQUE KEY uk_identity_tenant(tenant_id,id),
 UNIQUE KEY uk_store_identity(tenant_id,provider_code,identity_scope,external_id),
 KEY ix_identity_store(tenant_id,store_id),
 FOREIGN KEY(tenant_id,store_id) REFERENCES crm_store_master(tenant_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

