CREATE TABLE crm_pool_policy (
 id BIGINT NOT NULL,
 tenant_id VARCHAR(64) NOT NULL,
 revision BIGINT NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 created_by VARCHAR(64) NOT NULL,
 updated_by VARCHAR(64) NOT NULL,
 policy_version INT NOT NULL,
 first_visit_hours SMALLINT UNSIGNED NOT NULL DEFAULT 24,
 followup_days SMALLINT UNSIGNED NOT NULL DEFAULT 7,
 cooperating_days SMALLINT UNSIGNED NOT NULL DEFAULT 60,
 return_cooldown_hours SMALLINT UNSIGNED NOT NULL DEFAULT 48,
 status_code VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
 effective_from DATETIME(6) NULL,
 published_at DATETIME(6) NULL,
 published_by VARCHAR(64) NULL,
 description VARCHAR(500) NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uk_pool_policy_tenant(tenant_id,id),
 UNIQUE KEY uk_pool_policy_version(tenant_id,policy_version),
 UNIQUE KEY uk_pool_policy_effective(tenant_id,effective_from),
 KEY ix_pool_policy_status(tenant_id,status_code,effective_from,id),
 CHECK(first_visit_hours>0 AND followup_days>0 AND cooperating_days>0 AND return_cooldown_hours>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

